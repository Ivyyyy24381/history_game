def to_xy(lat, lon):
    """经纬度 → 地图百分比坐标（左上角为 0,0）。"""
    x = (lon - LON0) / (LON1 - LON0) * 100.0
    y = (LAT1 - lat) / (LAT1 - LAT0) * 100.0
    return round(x, 1), round(y, 1)


def city_xy(name):
    lat, lon = CITIES[name]
    return to_xy(lat, lon)


def aspect():
    """画布该用的宽高比：让经度方向按中纬度余弦压缩后不变形。"""
    return ((LON1 - LON0) * cos(radians(MIDLAT))) / (LAT1 - LAT0)


